#!/usr/bin/env python3
"""Turns the output of scripts/gen-profile-corpus.lua into src/Tests/Fixtures/ProfileCorpusExpected.lua.

Usage: python scripts/gen-profile-corpus.py <run-in-roblox output file>
"""
import sys

lines = [l.rstrip("\r\n") for l in open(sys.argv[1], encoding="utf-8", errors="ignore")]
entries = []
for l in lines:
    if l.startswith("EXPECT\t"):
        _, name, migrated, encoded = l.split("\t")
        entries.append((name, migrated, encoded))
if not any(l.startswith("EXPECT-DONE") for l in lines):
    sys.exit("generator did not finish (no EXPECT-DONE)")
if len({e[0] for e in entries}) != len(entries):
    sys.exit("duplicate case names")

out = ["--!strict", "-- GENERATED by scripts/gen-profile-corpus.py from scripts/gen-profile-corpus.lua. Do not edit by hand.",
       "-- Digests (Tests/TestHelpers/Canonical.lua) of what PlayerDataSystem made of each ProfileCorpus case BEFORE the profile",
       "-- fields moved out of it. { migrated record, re-encoded profile }.", "return {"]
for name, migrated, encoded in entries:
    out.append('\t["%s"] = { "%s", "%s" },' % (name, migrated, encoded))
out.append("}")
open("src/Tests/Fixtures/ProfileCorpusExpected.lua", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", len(entries), "entries")
